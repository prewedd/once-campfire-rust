// Settings modal, notifications menu, Slack-style profile panel.  node ui4.e2e.js <scratchpad> <base> <join code> <out>
const path = require("path")
const [, , S, BASE, CODE, OUT] = process.argv
const { chromium } = require("playwright")
const t = Date.now().toString(36) + Math.random().toString(36).slice(2, 5)
const results = [], errors = []
const check = (name, ok, detail = "") => { results.push(!!ok); console.log(`${ok ? "PASS" : "FAIL"} ${name}${detail ? " — " + detail : ""}`) }
let shot = 0
async function step(name, fn) { try { await fn() } catch (e) { check(name, false, String(e.message).split("\n")[0]); for (const p of globalThis.pages ?? []) await p.screenshot({ path: `${OUT}/ui4-fail-${++shot}.png` }).catch(() => {}) } }
async function join(b, name) {
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, permissions: ["notifications"] })).newPage()
  p.on("console", m => m.type() === "error" && !/Failed to load resource|Failed to fetch/.test(m.text()) && errors.push(`${name}: ${m.text().split("\n")[0]}`))
  p.on("pageerror", e => e.name !== "AbortError" && errors.push(`${name}: ${e.message}`))
  await p.goto(`${BASE}/join/${CODE}`)
  await p.fill('input[name="user[name]"]', name)
  await p.fill('input[name="user[email_address]"]', `${name.toLowerCase()}${t}@x.test`)
  await p.fill('input[name="user[password]"]', "secret-password-" + t)
  await Promise.all([p.waitForURL(/rooms\/\d+/), p.locator('input[name="user[password]"]').press("Enter")])
  if (!p.url().endsWith("/rooms/1")) await p.goto(`${BASE}/rooms/1`)
  await p.waitForLoadState("networkidle")
  return p
}
;(async () => {
  const b = await chromium.launch()
  const ana = await join(b, `Ana${t}`), ben = await join(b, `Ben${t}`)
  const room = ana.url()
  globalThis.pages = [ana]

  await step("settings modal", async () => {
    await ana.locator('#sidebar a[href$="/users/me/profile"]').first().click()
    const modal = ana.locator("dialog.ws-modal[open]")
    await modal.locator(".ws-modal__body form").first().waitFor({ timeout: 8000 })
    check("your profile settings open in a modal", ana.url() === room, ana.url())
    check("…titled", (await modal.locator(".ws-modal__title").innerText()).length > 0, await modal.locator(".ws-modal__title").innerText())
    await ana.screenshot({ path: `${OUT}/ui4-modal-profile.png` })
    const name = modal.locator('input[name="user[name]"]')
    await name.fill(`Ana Renamed ${t}`)
    await name.press("Enter")
    await ana.waitForTimeout(1200)
    check("saving keeps you in the modal or returns to the room", ana.url() === room, ana.url())
    await ana.keyboard.press("Escape")
    await modal.waitFor({ state: "detached", timeout: 2000 }).catch(() => {})
    await ana.waitForLoadState("networkidle")
    check("Escape closes it", (await ana.locator("dialog.ws-modal[open]").count()) === 0)
    await ana.locator('#sidebar a[href$="/users/me/profile"]').first().click()
    await ana.locator('dialog.ws-modal[open] input[name="user[name]"]').waitFor({ timeout: 8000 })
    check("the change was saved", (await ana.locator('dialog.ws-modal[open] input[name="user[name]"]').inputValue()) === `Ana Renamed ${t}`)
    check("…and the modal's title says what it is", (await ana.locator("dialog.ws-modal .ws-modal__title").innerText()) === "Your profile")
    await ana.keyboard.press("Escape")
    await ana.locator('#nav a[href$="/edit"][data-room-id]').click()
    await ana.locator("dialog.ws-modal[open] .ws-modal__body form").first().waitFor({ timeout: 8000 })
    check("room settings open in a modal too", ana.url() === room)
    await ana.screenshot({ path: `${OUT}/ui4-modal-room.png` })
    await ana.locator("dialog.ws-modal [data-modal-close]").click()
    check("✕ closes it", (await ana.locator("dialog.ws-modal[open]").count()) === 0)
  })

  await step("notifications menu", async () => {
    // The bell's frame loads once push notifications are ready, which headless Chromium never is.
    await ana.evaluate(() => { const frame = document.querySelector('#nav turbo-frame[id^="involvement_"]'); frame.src = frame.querySelector("[data-turbo-frame-url-param]")?.dataset.turboFrameUrlParam ?? frame.dataset.turboFrameUrlParam })
    const bell = ana.locator('#nav form[action*="/involvement"] button')
    await bell.waitFor({ timeout: 8000 })
    check("the bell says what it's set to", /^Notifications: /.test(await bell.getAttribute("title")), await bell.getAttribute("title"))
    await bell.click()
    const menu = ana.locator(".involvement-menu")
    await menu.waitFor({ timeout: 3000 })
    check("clicking it opens a menu of choices", (await menu.locator("[data-involvement]").count()) === 4)
    check("…each explained", (await menu.innerText()).includes("Only when someone @mentions me"))
    await ana.screenshot({ path: `${OUT}/ui4-notifications.png` })
    await menu.locator('[data-involvement="everything"]').click({ timeout: 4000 }).catch(e => console.log(e.message.split("\n").slice(0, 14).join("\n")))
    await ana.waitForFunction(() => document.querySelector('#nav form[action*="/involvement"] button')?.classList.contains("everything"), null, { timeout: 8000 })
    check("choosing one sets it", true)
    await ana.waitForFunction(() => document.querySelector('#nav form[action*="/involvement"] button')?.title === "Notifications: All messages", null, { timeout: 4000 })
    check("…and the bell says so", true)
  })

  await step("profile panel", async () => {
    const anaId = await ana.evaluate(() => Current.user.id)
    await ben.locator("#composer lexxy-editor").click(); await ben.keyboard.type(`hello ${t}`); await ben.keyboard.press("Enter")
    const msg = ana.locator(".message[data-message-id]", { hasText: `hello ${t}` }).first()
    await msg.waitFor({ timeout: 8000 })
    await msg.locator(".message__avatar a").click()
    const pane = ana.locator(".flexpane:not([hidden])")
    await pane.locator(".profile-pane__name").waitFor({ timeout: 8000 })
    check("a profile opens in the panel", (await pane.locator(".profile-pane__name").innerText()).includes(`Ben${t}`))
    check("…with Message", (await pane.locator(".profile-pane__btn--primary").innerText()).includes("Message"))
    check("…and presence", (await pane.locator(".presence-status").getAttribute("data-presence")) === "online")
    await ana.screenshot({ path: `${OUT}/ui4-profile-pane.png` })
    await ana.evaluate(id => document.querySelector("#flexpane").src = `/users/${id}`, anaId)
    await pane.locator(".profile-pane__btn", { hasText: "Edit profile" }).waitFor({ timeout: 8000 })
    check("your own has Edit profile", true)
    await pane.locator(".profile-pane__btn", { hasText: "Edit profile" }).click()
    await ana.locator("dialog.ws-modal[open] .ws-modal__body form").first().waitFor({ timeout: 8000 })
    check("…which opens the settings modal", true)
    await ana.keyboard.press("Escape")
  })

  await step("reorder channels", async () => {
    await ana.goto(`${BASE}/rooms/1`); await ana.waitForLoadState("networkidle")
    const names = () => ana.$$eval("#shared_rooms > [data-room-id]", items => items.map(item => item.dataset.roomId))
    const before = await names()
    const last = ana.locator("#shared_rooms > [data-room-id]").nth(2)
    const first = ana.locator("#shared_rooms > [data-room-id]").first()
    await last.dragTo(first, { targetPosition: { x: 10, y: 2 } })
    await ana.waitForTimeout(600)
    const after = await names()
    check("dragging a channel moves it", after[0] === before[2] && after[1] === before[0], `${before.slice(0, 3)} → ${after.slice(0, 3)}`)
    await ana.reload(); await ana.waitForLoadState("networkidle")
    const reloaded = await names()
    check("…and the order is kept", reloaded.join() === after.join(), `${reloaded.slice(0, 3)} vs ${after.slice(0, 3)}`)
    await ana.locator(`#shared_rooms > [data-room-id="${reloaded[0]}"]`).focus()
    await ana.keyboard.press("Alt+ArrowDown")
    await ana.waitForTimeout(500)
    check("Alt+↓ moves one down", (await names())[1] === reloaded[0])
    const benOrder = await ben.$$eval("#shared_rooms > [data-room-id]", items => items.map(item => item.dataset.roomId))
    check("…for that person only", benOrder[0] !== reloaded[0] || before[0] === reloaded[0])
  })

  check("no JavaScript errors", errors.length === 0, errors.slice(0, 4).join(" | "))
  await b.close()
  console.log(`\n${results.filter(Boolean).length}/${results.length} checks passed`)
  process.exit(results.every(Boolean) ? 0 : 1)
})()
